// Dashboard KPI Summary
export const getDashboardKPIs = () => {
  const today = mockAnalyticsData[mockAnalyticsData.length - 1];
  const yesterday = mockAnalyticsData[mockAnalyticsData.length - 2];

  return {
    total_calls_today: today.calls_completed,
    total_conversions_today: today.conversions,
    conversion_rate_today: today.conversion_rate,
    active_agents: mockAgents.filter((a) => a.status === 'active').length,
    active_campaigns: mockCampaigns.filter((c) => c.status === 'active').length,
    calls_comparison:
      ((today.calls_completed - yesterday.calls_completed) /
        yesterday.calls_completed) *
      100,
    conversion_comparison:
      ((today.conversions - yesterday.conversions) / yesterday.conversions) *
      100,
    total_revenue: today.total_revenue,
    average_call_duration: today.average_duration,
  };
};

// Get agent by ID
